const TEXT: Record<Lang, Record<RouteKey, string>> = { en: EN, es: ES };

export function routeText(lang: Lang, key: RouteKey, params: Record<string, string | number> = {}): string {
  return TEXT[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

export function kindText(lang: Lang, kind: WayKind): string {
  return routeText(lang, `k_${kind}` as RouteKey);
}

/** A local record id, a state code or a Census place name, as the answer names it. */
function whoText(by: string, lang: Lang): string {
  if (/^[A-Z]{2}$/.test(by)) return stateName(by, lang);
  if (/^[a-z_]+$/.test(by)) return placeName(by, lang);
  return by;
}

/** One plain sentence for one reason a piece of the route can't be a YES. */
export function reasonText(reason: PieceReason, lang: Lang, wayName: string | null): string {
  const name = wayName ?? routeText(lang, "unnamed");
  const where = reason.where && reason.where !== "everywhere" ? routeText(lang, `w_${reason.where}` as RouteKey) : routeText(lang, "w_other");
  return routeText(lang, `r_${reason.code}` as RouteKey, {
    state: whoText(reason.by, lang),
    place: whoText(reason.by, lang),
    kind: kindText(lang, reason.kind),
    where,
    facility: reason.facility ?? name,
    name,
  });
}
