const UI: Record<Lang, Record<UiKey, string>> = { en, es };

export function t(lang: Lang, key: UiKey, params: Record<string, string | number> = {}): string {
  let text = UI[lang][key] ?? UI.en[key];
  for (const [k, v] of Object.entries(params)) text = text.replace(`{${k}}`, String(v));
  return text;
}

/**
 * The title split before its last word, so the page can set that word in a block of its own:
 * "Is it an " and "e-bike?", or "¿Es una bicicleta " and "eléctrica?".
 */
export function titleParts(text: string): [lead: string, key: string] {
  const at = text.lastIndexOf(" ");
  return at < 0 ? ["", text] : [text.slice(0, at + 1), text.slice(at + 1)];
}

/** Every interface string key, for tests. */
export const UI_KEYS = Object.keys(en) as UiKey[];

export function isUiKey(key: string): key is UiKey {
  return key in en;
}

/**
 * What a screen reader hears after a link, pasted text or label photo is read: how many facts
 * were read, that each is marked, and that the answer can't say YES until they are checked.
 * Empty when nothing was read, since the reader's own error already says so.
 */
export function readAnnouncement(lang: Lang, total: number): string {
  if (total <= 0) return "";
  return total === 1 ? t(lang, "readAnnounceOne") : t(lang, "readAnnounceMany", { total });
}
