const TEXT: Record<Lang, Record<FinderKey, string>> = { en, es };

export function finderText(lang: Lang, key: FinderKey, params: Record<string, string | number> = {}): string {
  return TEXT[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

export const purposeText = (lang: Lang, use: Use) => finderText(lang, `use_${use}` as FinderKey);
export const budgetText = (lang: Lang, budget: Budget) => finderText(lang, `budget_${budget}` as FinderKey);
export const colorText = (lang: Lang, color: ColorFamily) => finderText(lang, `color_${color}` as FinderKey);
export const topicText = (lang: Lang, q: QuestionId) => finderText(lang, `topic_${q}` as FinderKey);

/** A height in inches as feet and inches, like 4'11". */
export function feetInches(inches: number): string {
  return `${Math.floor(inches / 12)}'${inches % 12}"`;
}

