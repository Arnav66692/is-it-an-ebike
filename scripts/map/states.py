def tiles(box, rows, cols):
    s, w, n, e = box
    dy, dx = (n - s) / rows, (e - w) / cols
    return [(round(s + r * dy, 4), round(w + c * dx, 4), round(s + (r + 1) * dy, 4), round(w + (c + 1) * dx, 4))
            for r in range(rows) for c in range(cols)]
